"""Restore active veterans to their FIFA19 peak attributes.

The data comes from ``data/fifa19_peak.csv`` (generated by
``tools/export_fifa19_peak.py`` from the FIFA19 rows of the project's players.db).

Selection rules - deliberately *not* "everyone", and safe against the traps found
while doing this by hand on a real save:

* only currently active players (age >= ``min_age``), male, and *not* part of the
  legend/ICON set - those belong to :class:`~services.legend_service.LegendService`;
* only players whose FIFA19 peak OVR is **higher** than what the save has now, so
  a player who peaked after 2019 is never touched;
* ``nationality`` and ``height`` must match the FIFA19 row, which keeps same-name
  players (a 192cm "De Bruyne" at Fiorentina, a 185cm "Jan Oblak") from being
  mistaken for the star;
* players whose club disappeared from the current data version (Neymar,
  James Rodríguez, Alex Sandro, ...) still count as active when
  ``include_clubless`` is on;
* writes are **raise only** by default: an attribute is only overwritten when the
  FIFA19 value is higher, so no player can be weakened.
"""

from __future__ import annotations

import csv
import datetime
from pathlib import Path

from core.name_resolver import NameResolver
from core.sav_file import SavFile
from .birthdates import EPOCH
from .changes import ChangeSet, FieldChange

#: FIFA19's highest regular rating; anything above is an ICON/promo record.
PEAK_MAX = 94

#: Same-name players that a pure data match would mistake for the star:
#: 193080 is a 192cm "De Bruyne" at Fiorentina and 192387 a 185cm "Jan Oblak" at
#: Paris FC - different people from 192985 / 200389, who are already included.
SAME_NAME_IDS = {193080, 192387}

#: FC26 men's national team ids - a link to one of these is not a club.
NATIONAL_TEAM_IDS = {
    974, 1318, 1322, 1325, 1328, 1330, 1331, 1334, 1335, 1337, 1341, 1343, 1352, 1353, 1354,
    1355, 1356, 1359, 1362, 1363, 1364, 1365, 1366, 1367, 1369, 1370, 1375, 1377, 1386, 1387,
    1391, 1411, 1415, 1667, 105013, 110081, 111099, 111109, 111111, 111112, 111114, 111115,
    111130, 111448, 111455, 111456, 111462, 111465, 111473, 111475, 111485, 111510, 111512,
    111513, 111527, 111545, 112048, 112054,
}


class PeakRestoreService:
    """Stage "restore active veterans to peak" edits for the loaded save."""

    TABLE = "CZUM"
    KEY = "playerid"
    LINK_TABLE = "RrqT"
    FREE_AGENT_TEAM_ID = 111592
    ICON_LIST = Path(__file__).resolve().parent.parent / "data" / "icon_hero_list.csv"
    PEAK_DATA = Path(__file__).resolve().parent.parent / "data" / "fifa19_peak.csv"
    EXTRA_LEGENDS = (82092, 191190)

    FIELDS = [
        "overallrating", "potential", "finishing", "dribbling", "ballcontrol", "sprintspeed",
        "acceleration", "shotpower", "shortpassing", "longpassing", "vision", "composure",
        "agility", "balance", "jumping", "strength", "headingaccuracy", "standingtackle",
        "slidingtackle", "interceptions", "curve", "freekickaccuracy", "penalties", "volleys",
        "positioning", "crossing", "longshots", "stamina", "reactions", "aggression",
        "defensiveawareness", "gkdiving", "gkhandling", "gkkicking", "gkpositioning", "gkreflexes",
        "weakfootabilitytypecode", "skillmoves", "skillmoveslikelihood", "preferredfoot",
        "internationalrep",
    ]

    #: Goalkeeper-only attributes; never written to outfield players.
    GK_FIELDS = ("gkdiving", "gkhandling", "gkkicking", "gkpositioning", "gkreflexes")

    def __init__(self, sav: SavFile):
        if not sav.db:
            raise ValueError("存档尚未加载")
        self.sav = sav
        self.players = sav.db.get_table(self.TABLE)
        if not self.players:
            raise ValueError("存档中没有球员表 CZUM")
        self.resolver = NameResolver(sav.db)
        self._peak = None
        self._legend_ids = None
        self._player_teams = {}
        links = sav.db.get_table(self.LINK_TABLE)
        if links:
            for record in links.records:
                player_id = record.get(self.KEY, 0)
                team_id = record.get("teamid", 0)
                if player_id and team_id:
                    self._player_teams.setdefault(player_id, []).append(team_id)

    # ------------------------------------------------------------------
    # data
    # ------------------------------------------------------------------
    @staticmethod
    def _as_int(value):
        try:
            return int(str(value).strip())
        except (TypeError, ValueError):
            return 0

    def _load_peak(self):
        if self._peak is not None:
            return self._peak
        if not self.PEAK_DATA.is_file():
            raise ValueError(
                "缺少 FIFA19 巅峰数据 data/fifa19_peak.csv，"
                "请先运行 python tools/export_fifa19_peak.py"
            )
        peak = {}
        with self.PEAK_DATA.open("r", encoding="utf-8", newline="") as handle:
            for row in csv.DictReader(handle):
                player_id = self._as_int(row.get("playerid"))
                if not player_id:
                    continue
                values = {field: self._as_int(row.get(field)) for field in self.FIELDS}
                peak[player_id] = {
                    "values": values,
                    "nationality": self._as_int(row.get("nationality")),
                    "height": self._as_int(row.get("height")),
                    "position": self._as_int(row.get("preferredposition1")),
                    "name": (row.get("name") or "").strip(),
                    "peak": values["overallrating"],
                }
        self._peak = peak
        return peak

    def legend_ids(self):
        if self._legend_ids is not None:
            return self._legend_ids
        ids = set(self.EXTRA_LEGENDS)
        if self.ICON_LIST.is_file():
            with self.ICON_LIST.open("r", encoding="utf-8-sig", newline="") as handle:
                for row in csv.DictReader(handle):
                    raw = (row.get("IDs") or "").strip()
                    if raw.isdigit():
                        ids.add(int(raw))
        self._legend_ids = ids
        return ids

    def club_teams(self, player_id):
        """Team ids that are neither the free-agent pool nor a national team."""
        teams = []
        for team_id in self._player_teams.get(player_id, []):
            if team_id == self.FREE_AGENT_TEAM_ID:
                continue
            if team_id in NATIONAL_TEAM_IDS or self.resolver.is_national_team(team_id):
                continue
            teams.append(team_id)
        return teams

    # ------------------------------------------------------------------
    # selection
    # ------------------------------------------------------------------
    def raiseable_fields(self, record, entry):
        """Peak attributes that are strictly higher than what the save holds."""
        is_gk = entry.get("position") == 0 or (record.get("preferredposition1") or 0) == 0
        values = entry["values"]
        result = []
        for field in self.FIELDS:
            if field in self.GK_FIELDS and not is_gk:
                continue
            target = values.get(field) or 0
            if not target:
                continue
            if target > (record.get(field, 0) or 0):
                result.append(field)
        return result

    def is_non_player_record(self, player_id) -> bool:
        """Manager/placeholder records (only linked to 5v5/Rush or manager pools)."""
        team_ids = self._player_teams.get(player_id) or []
        if not team_ids:
            return False
        if not any(self.resolver.is_non_player_team(team_id) for team_id in team_ids):
            return False
        return all(
            self.resolver.is_national_team(team_id) or self.resolver.is_non_player_team(team_id)
            for team_id in team_ids
        )

    def candidates(self, min_peak: int = 85, min_age: int = 30, include_clubless: bool = True,
                   skip_same_name: bool = True, include_done: bool = False):
        peak_data = self._load_peak()
        legends = self.legend_ids()
        found = []
        for record in self.players.records:
            player_id = record.get(self.KEY, 0)
            if not isinstance(player_id, int) or player_id <= 0 or player_id in legends:
                continue
            if skip_same_name and player_id in SAME_NAME_IDS:
                continue
            if self.is_non_player_record(player_id):
                continue
            entry = peak_data.get(player_id)
            if not entry:
                continue
            current_ovr = record.get("overallrating", 0) or 0
            target_ovr = entry["peak"]
            if target_ovr < min_peak or target_ovr > PEAK_MAX:
                continue
            if (record.get("gender", 0) or 0) != 0:
                continue
            if entry["nationality"] and entry["nationality"] != (record.get("nationality") or 0):
                continue
            if entry["height"] and abs(entry["height"] - (record.get("height") or 0)) > 3:
                continue
            birthdate = record.get("birthdate", 0) or 0
            try:
                age = 2026 - (EPOCH + datetime.timedelta(days=int(birthdate))).year
            except (TypeError, ValueError, OverflowError):
                continue
            if age < min_age:
                continue
            clubs = self.club_teams(player_id)
            if not clubs and not include_clubless:
                continue
            # OVR 已经到巅峰、但仍有单项属性低于巅峰的球员同样要恢复（例如德佩）。
            raiseable = self.raiseable_fields(record, entry)
            if not raiseable and not include_done:
                continue
            found.append({
                "playerid": player_id,
                "name": self.resolver.get_name(record),
                "age": age,
                "overallrating": current_ovr,
                "peak": target_ovr,
                "gain": max(0, target_ovr - current_ovr),
                "raiseable": len(raiseable),
                "done": not raiseable,
                "gk": entry.get("position") == 0 or (record.get("preferredposition1") or 0) == 0,
                "club": ", ".join(self.resolver.get_team_name(team) for team in clubs),
                "clubless": not clubs,
            })
        if include_done:
            # 待恢复的排在前面，已达标的后置
            found.sort(key=lambda item: (item["done"], -item["peak"], -item["raiseable"], item["name"]))
        else:
            found.sort(key=lambda item: (-item["peak"], -item["raiseable"], item["name"]))
        return found

    def preview(self, min_peak: int = 85, min_age: int = 30, include_clubless: bool = True,
                skip_same_name: bool = True, include_done: bool = False):
        candidates = self.candidates(
            min_peak=min_peak, min_age=min_age, include_clubless=include_clubless,
            skip_same_name=skip_same_name, include_done=include_done,
        )
        return {
            "count": sum(1 for item in candidates if not item["done"]),
            "roster_count": len(candidates),
            "min_peak": min_peak,
            "min_age": min_age,
            "include_clubless": include_clubless,
            "skip_same_name": skip_same_name,
            "clubless_count": sum(1 for item in candidates if item["clubless"]),
            "ovr_unchanged_count": sum(1 for item in candidates if not item["gain"] and not item["done"]),
            "gk_count": sum(1 for item in candidates if item["gk"] and not item["done"]),
            "include_done": include_done,
            "candidates": candidates,
        }

    # ------------------------------------------------------------------
    # apply
    # ------------------------------------------------------------------
    def apply(self, min_peak: int = 85, min_age: int = 30, include_clubless: bool = True,
              only_raise: bool = True, skip_same_name: bool = True):
        candidates = self.candidates(
            min_peak=min_peak, min_age=min_age, include_clubless=include_clubless,
            skip_same_name=skip_same_name,
        )
        peak_data = self._load_peak()
        by_id = {record.get(self.KEY): record for record in self.players.records}
        changes = ChangeSet()
        restored = []
        field_total = 0
        for item in candidates:
            record = by_id.get(item["playerid"])
            if record is None:
                continue
            entry = peak_data[item["playerid"]]
            values = entry["values"]
            is_gk = entry.get("position") == 0 or (record.get("preferredposition1") or 0) == 0
            touched = 0
            for field in self.FIELDS:
                if field in self.GK_FIELDS and not is_gk:
                    continue
                target = values.get(field) or 0
                if not target:
                    continue
                current = record.get(field, 0) or 0
                if target == current or (only_raise and target < current):
                    continue
                record[field] = target
                changes.add(FieldChange(
                    self.TABLE, self.KEY, item["playerid"], field, current, target,
                ))
                touched += 1
            if touched:
                field_total += touched
                restored.append({
                    **item,
                    "fields": touched,
                    "overallrating_after": record.get("overallrating", 0),
                })
        return changes, {
            "candidate_count": len(candidates),
            "restored_count": len(restored),
            "field_count": field_total,
            "only_raise": only_raise,
            "restored": restored,
        }
